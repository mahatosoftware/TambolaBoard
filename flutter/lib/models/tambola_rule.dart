enum TambolaRuleType {
  earlyFive,
  topLine,
  middleLine,
  bottomLine,
  fullHouse,
  secondHouse,
  thirdHouse,
  corner,
  diamond,
  pyramid,
  invertedPyramid,
  star,
  odds,
  even,
  firstHalf,
  secondHalf,
  breakfast,
  lunch,
  dinner,
  temperature,
  belowFifty,
  aboveFifty,
}

class TambolaRule {
  final int id;
  final String name;
  final String description;
  final TambolaRuleType type;
  final List<int> winningPattern;
  final int quantity;
  final int percentage;
  final int weight;
  final bool isFullHouse;

  TambolaRule({
    required this.id,
    required this.name,
    required this.description,
    required this.type,
    required this.winningPattern,
    this.quantity = 1,
    this.percentage = 0,
    this.weight = 1,
    this.isFullHouse = false,
  });

  TambolaRule copyWith({
    int? id,
    String? name,
    String? description,
    TambolaRuleType? type,
    List<int>? winningPattern,
    int? quantity,
    int? percentage,
    int? weight,
    bool? isFullHouse,
  }) {
    return TambolaRule(
      id: id ?? this.id,
      name: name ?? this.name,
      description: description ?? this.description,
      type: type ?? this.type,
      winningPattern: winningPattern ?? this.winningPattern,
      quantity: quantity ?? this.quantity,
      percentage: percentage ?? this.percentage,
      weight: weight ?? this.weight,
      isFullHouse: isFullHouse ?? this.isFullHouse,
    );
  }
}

