  String translate(String key, [List<dynamic>? args]) {
    final languageCode = locale.languageCode;
    final map = _localizedValues[languageCode] ?? _localizedValues['en']!;
    var value = map[key] ?? _localizedValues['en']![key] ?? key;
    if (args != null) {
      for (int i = 0; i < args.length; i++) {
        value = value.replaceAll('{$i}', args[i].toString());
      }
    }
    return value;
  }
