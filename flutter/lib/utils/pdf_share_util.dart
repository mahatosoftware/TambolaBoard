import 'package:flutter/material.dart';
import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import '../models/winning_prize_entity.dart';

class PdfShareUtil {
  static Future<void> generateAndShareWinnerPdf(
    BuildContext context,
    List<WinningPrizeEntity> winners, [
    String gameId = "",
  ]) async {
    if (winners.isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text("No winners to share!")),
      );
      return;
    }

    try {
      final pdf = pw.Document();
      final dateStr = DateFormat("dd MMM yyyy, hh:mm a").format(DateTime.now());
      final subText = gameId.isNotEmpty
          ? "Game ID: $gameId  |  Date: $dateStr"
          : "Date: $dateStr";

      pdf.addPage(
        pw.Page(
          pageFormat: PdfPageFormat.a4,
          build: (pw.Context context) {
            return pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.center,
              children: [
                pw.Text(
                  "TAMBOLA BOARD - WINNER LIST",
                  style: pw.TextStyle(
                    color: PdfColor.fromHex("#1B5E20"),
                    fontSize: 22,
                    fontWeight: pw.FontWeight.bold,
                  ),
                ),
                pw.SizedBox(height: 8),
                pw.Text(
                  subText,
                  style: const pw.TextStyle(
                    color: PdfColors.grey700,
                    fontSize: 12,
                  ),
                ),
                pw.SizedBox(height: 20),
                pw.TableHelper.fromTextArray(
                  headers: ["Prize / Rule Name", "Winner(s)", "Status"],
                  data: winners.map((item) {
                    final winnerName = item.winnerName == null || item.winnerName!.isEmpty
                        ? "Pending Claim"
                        : item.winnerName!;
                    final status = item.isClaimed ? "Claimed" : "Unclaimed";
                    return [item.savedRule.ruleName, winnerName, status];
                  }).toList(),
                  headerStyle: pw.TextStyle(
                    color: PdfColor.fromHex("#0D47A1"),
                    fontWeight: pw.FontWeight.bold,
                    fontSize: 13,
                  ),
                  headerDecoration: pw.BoxDecoration(
                    color: PdfColor.fromHex("#E3F2FD"),
                  ),
                  cellStyle: const pw.TextStyle(
                    fontSize: 12,
                  ),
                  cellHeight: 28,
                  cellAlignments: {
                    0: pw.Alignment.centerLeft,
                    1: pw.Alignment.centerLeft,
                    2: pw.Alignment.centerLeft,
                  },
                ),
                pw.Spacer(),
                pw.Text(
                  "Generated by Tambola Board App",
                  style: const pw.TextStyle(
                    color: PdfColors.grey,
                    fontSize: 10,
                  ),
                ),
              ],
            );
          },
        ),
      );

      final subjectText = gameId.isNotEmpty
          ? "Tambola Winner List (Game Code: $gameId)"
          : "Tambola Board Winner List";

      await Printing.sharePdf(
        bytes: await pdf.save(),
        filename: "Tambola_Winners.pdf",
        subject: subjectText,
      );
    } catch (e) {
      if (context.mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text("Error generating PDF: $e")),
        );
      }
    }
  }
}
